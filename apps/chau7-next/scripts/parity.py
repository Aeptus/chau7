#!/usr/bin/env python3
"""Parity summary for Chau7 Next, computed from docs/rust-port/inventory/.

scripts/parity.py            print the summary table
scripts/parity.py --write    rewrite the generated block in docs/rust-port/PARITY.md
scripts/parity.py --check    exit 1 if a row is malformed, an ID repeats,
                             or PARITY.md is out of date (CI runs this)
scripts/parity.py --todo M   list the rows of module M that are not done
scripts/parity.py --set ID STATUS [RUST]
                             set a row's status (and Rust column), for
                             example: --set OVL-006 done chau7_next/src/workspace/tab_bar_view.rs
"""

import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
INVENTORY = ROOT / "docs/rust-port/inventory"
PARITY = ROOT / "docs/rust-port/PARITY.md"
BEGIN, END = "<!-- parity:begin -->", "<!-- parity:end -->"
STATUSES = ("done", "partial", "missing", "n/a", "dropped")
ROW = re.compile(r"^\|\s*[A-Z0-9]{3}-\d{3}\s*\|")
CELL_SPLIT = re.compile(r"(?<!\\)\|")


def modules():
    for path in sorted(INVENTORY.glob("*.md")):
        if path.stem in ("FORMAT", "README"):
            continue
        yield path


def rows(path):
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if ROW.match(line):
            cells = [c.strip() for c in CELL_SPLIT.split(line.strip().strip("|"))]
            yield number, cells


def wave(path):
    match = re.search(r"^Wave:\s*(.*)$", path.read_text(), re.M)
    if not match:
        return "?"
    digit = re.match(r"\d", match.group(1))
    return digit.group(0) if digit else "per row"


def collect():
    problems, seen, table = [], {}, []
    for path in modules():
        text = path.read_text()
        if "\u2014" in text:
            problems.append(f"{path.name}: contains an em dash")
        counts = collections.Counter()
        mac = 0
        for number, cells in rows(path):
            where = f"{path.name}:{number}"
            if len(cells) != 7:
                problems.append(f"{where}: {len(cells)} cells, expected 7")
                continue
            ident, status = cells[0], cells[5].strip("`* ").lower()
            if ident in seen:
                problems.append(f"{where}: {ident} also at {seen[ident]}")
            seen[ident] = where
            if status not in STATUSES:
                problems.append(f"{where}: unknown status {status!r}")
            counts[status] += 1
            if cells[6] and status not in ("done", "n/a", "dropped"):
                mac += 1
        table.append((path.stem, wave(path), counts, mac))
    return table, problems


def summary(table):
    total = collections.Counter()
    lines = [
        "| Module | Wave | Rows | done | partial | missing | n/a | dropped | Left with macOS APIs |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, wave_, counts, mac in table:
        total += counts
        n = sum(counts.values())
        lines.append(
            f"| [{name}](inventory/{name}.md) | {wave_} | {n} | "
            + " | ".join(str(counts[s]) for s in STATUSES)
            + f" | {mac} |"
        )
    n = sum(total.values())
    done = total["done"] + total["n/a"] + total["dropped"]
    lines.append(f"| **Total** | | **{n}** | " + " | ".join(f"**{total[s]}**" for s in STATUSES) + " | |")
    lines.append("")
    lines.append(
        f"Finished (done, n/a or dropped): {done} of {n} rows "
        f"({100 * done // max(n, 1)}%). Partial: {total['partial']}."
    )
    return "\n".join(lines)


def generated_block(table):
    return f"{BEGIN}\n<!-- Generated by apps/chau7-next/scripts/parity.py --write. Do not edit. -->\n\n{summary(table)}\n\n{END}"


def set_row(ident, status, rust):
    if status not in STATUSES:
        sys.exit(f"parity: unknown status {status!r}")
    for path in modules():
        lines = path.read_text().split("\n")
        for i, line in enumerate(lines):
            if not line.startswith(f"| {ident} "):
                continue
            cells = [c.strip() for c in CELL_SPLIT.split(line.strip().strip("|"))]
            if len(cells) != 7:
                sys.exit(f"parity: {path.name}: {ident} is malformed")
            cells[5] = status
            if rust is not None:
                cells[4] = rust
            lines[i] = "| " + " | ".join(cells) + " |"
            path.write_text("\n".join(lines))
            return
    sys.exit(f"parity: no row {ident}")


def main(argv):
    if "--set" in argv:
        i = argv.index("--set")
        ident, status = argv[i + 1], argv[i + 2]
        rust = argv[i + 3] if len(argv) > i + 3 and not argv[i + 3].startswith("--") else None
        set_row(ident, status, rust)
        # PARITY.md is regenerated separately (--write), so parallel branches
        # that each set rows do not all conflict on the generated table.
        return 0
    table, problems = collect()
    if "--todo" in argv:
        module = argv[argv.index("--todo") + 1]
        path = INVENTORY / f"{module}.md"
        for _, cells in rows(path):
            if len(cells) == 7 and cells[5].lower() in ("missing", "partial"):
                print(f"{cells[0]}  [{cells[5]}]  {cells[1]}")
        return 0
    if "--write" in argv:
        text = PARITY.read_text()
        start, end = text.index(BEGIN), text.index(END) + len(END)
        PARITY.write_text(text[:start] + generated_block(table) + text[end:])
    if "--check" in argv:
        text = PARITY.read_text()
        if generated_block(table) not in text:
            problems.append("docs/rust-port/PARITY.md is out of date: run apps/chau7-next/scripts/parity.py --write")
        for problem in problems:
            print(f"parity: {problem}", file=sys.stderr)
        return 1 if problems else 0
    if "--write" not in argv:
        print(summary(table))
    for problem in problems:
        print(f"parity: {problem}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
